"""
Visualization of a validated candidate profile (stage 4).

ProfileVisualizer receives the textX model produced by ProfileValidator
(never the raw text of the profile) and builds a short HTML page with:

    - the name of the candidate
    - contact information (emails and phones)
    - professional experience (years and entries)
    - education (degrees and fields of study)
    - skills grouped by category
    - the result of each profile, with the ACCEPTED ones highlighted

Because the input is the model, only profiles that already satisfy the
grammar and the semantic rules can be visualized.

Every value taken from the model is escaped with html.escape, so a name
such as "Tom <Admin> & Co" is shown as text and never interpreted as HTML.

See docs/08_grammar_design.md, Section 9.
"""

from html import escape


ACCEPTED = "ACCEPTED"

# Titles shown for each skill category of the grammar.
CATEGORY_TITLES = {
    "languages": "Languages",
    "frameworks": "Frameworks and libraries",
    "databases": "Databases",
    "tools": "Tools",
    "other": "Other",
}

STYLE = """
body { font-family: Arial, sans-serif; max-width: 760px; margin: 32px auto;
       padding: 0 16px; color: #222; background: #fafafa; }
h1 { margin-bottom: 4px; }
h2 { border-bottom: 2px solid #ddd; padding-bottom: 4px; margin-top: 28px; }
ul { padding-left: 20px; }
.empty { color: #888; font-style: italic; }
.token { display: inline-block; margin: 2px 4px 2px 0; padding: 2px 8px;
         border-radius: 10px; background: #e8eef7; font-family: monospace; }
table { border-collapse: collapse; width: 100%; }
th, td { text-align: left; padding: 6px 10px; border-bottom: 1px solid #ddd; }
tr.accepted { background: #dff3e3; font-weight: bold; }
tr.accepted td.result { color: #1b7a33; }
tr.rejected td.result { color: #a33; }
"""


class ProfileVisualizer:
    """
    Builds the HTML visualization of a validated candidate profile.
    """

    def render(self, model) -> str:
        """
        Build the HTML page of a candidate.

        Args:
            model: textX model returned by ProfileValidator.validate().

        Returns:
            Complete HTML document as a string.
        """

        name = escape(model.name)

        sections = [
            self._contact(model.contact),
            self._experience(model.experience),
            self._education(model.education),
            self._skills(model.skills),
            self._classification(model.classification),
        ]

        return "\n".join([
            "<!DOCTYPE html>",
            '<html lang="en">',
            "<head>",
            '<meta charset="utf-8">',
            f"<title>ResumeLens - {name}</title>",
            f"<style>{STYLE}</style>",
            "</head>",
            "<body>",
            f"<h1>{name}</h1>",
            "<p>Candidate profile generated by ResumeLens.</p>",
            *sections,
            "</body>",
            "</html>",
        ]) + "\n"

    # ---------------------------------------------------------------
    # Sections
    # ---------------------------------------------------------------

    @staticmethod
    def _contact(contact) -> str:
        items = [f"Email: {escape(e.value)}" for e in contact.emails]
        items += [f"Phone: {escape(p.value)}" for p in contact.phones]

        return _section("Contact", _list(items))

    @staticmethod
    def _experience(experience) -> str:
        if experience is None:
            return _section("Experience", _empty())

        years = f"<p>Years of experience: <strong>{experience.years}</strong></p>"
        entries = _list([escape(entry.text) for entry in experience.entries])

        return _section("Experience", years + "\n" + entries)

    @staticmethod
    def _education(education) -> str:
        if education is None:
            return _section("Education", _empty())

        items = []

        for item in education.items:
            kind = "Degree" if type(item).__name__ == "Degree" else "Field"
            items.append(f"{kind}: {escape(item.value)}")

        return _section("Education", _list(items))

    @staticmethod
    def _skills(skills) -> str:
        if skills is None:
            return _section("Skills", _empty())

        rows = []

        for category in skills.categories:
            title = CATEGORY_TITLES.get(category.category, category.category)
            tokens = "".join(
                f'<span class="token">{escape(token)}</span>'
                for token in category.tokens
            )
            rows.append(f"<tr><th>{escape(title)}</th><td>{tokens}</td></tr>")

        return _section("Skills", "<table>\n" + "\n".join(rows) + "\n</table>")

    @staticmethod
    def _classification(classification) -> str:
        rows = []

        for result in classification.results:
            css = "accepted" if result.result == ACCEPTED else "rejected"
            rows.append(
                f'<tr class="{css}"><td>{escape(result.profile)}</td>'
                f'<td class="result">{escape(result.result)}</td></tr>'
            )

        table = (
            "<table>\n<tr><th>Profile</th><th>Result</th></tr>\n"
            + "\n".join(rows)
            + "\n</table>"
        )

        return _section("Profile classification", table)


# -------------------------------------------------------------------
# HTML helpers
# -------------------------------------------------------------------

def _section(title: str, body: str) -> str:
    return f"<section>\n<h2>{title}</h2>\n{body}\n</section>"


def _list(items: list[str]) -> str:
    if not items:
        return _empty()

    return "<ul>\n" + "\n".join(f"<li>{item}</li>" for item in items) + "\n</ul>"


def _empty() -> str:
    return '<p class="empty">Not reported</p>'
