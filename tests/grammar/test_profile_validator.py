from pathlib import Path

import pytest
from textx.exceptions import TextXSemanticError, TextXSyntaxError

from src.model.grammar.profile_validator import ProfileValidator


VALIDATOR = ProfileValidator()
PROFILES = Path(__file__).resolve().parents[2] / "data" / "profiles"

VALID = (PROFILES / "valid_wednesday_addams.rl").read_text(encoding="utf-8")


def assert_rejected(text, error):
    with pytest.raises(error):
        VALIDATOR.validate(text)
    assert not VALIDATOR.is_valid(text)


# -------------------------------------------------------------------
# Valid profiles
# -------------------------------------------------------------------

def test_valid_example_files():
    wednesday = VALIDATOR.validate_file(PROFILES / "valid_wednesday_addams.rl")
    mary = VALIDATOR.validate_file(PROFILES / "valid_mary_jane_watson.rl")

    assert wednesday.name == "Wednesday Addams"
    assert mary.name == "Mary Jane Watson"
    assert VALIDATOR.is_valid(VALID)


def test_model_gives_access_to_every_block():
    model = VALIDATOR.validate(VALID)

    assert [e.value for e in model.contact.emails] == ["wednesday@mail.com"]
    assert [p.value for p in model.contact.phones] == ["+57 300 1234567"]
    assert model.experience.years == 3
    assert [e.text for e in model.experience.entries] == ["3 years of experience"]
    assert [(type(i).__name__, i.value) for i in model.education.items] == [
        ("Degree", "BACHELOR"),
        ("Field", "COMPUTER_SCIENCE"),
    ]
    assert {c.category: c.tokens for c in model.skills.categories} == {
        "languages": ["JAVASCRIPT"],
        "frameworks": ["REACT", "NODE_JS"],
        "databases": ["POSTGRESQL"],
        "tools": ["GIT"],
    }


def test_minimal_profile_is_valid():
    text = """
    candidate "Peter Parker" {
        contact { }
        classification {
            FULL_STACK_DEVELOPER: REJECTED
            MACHINE_LEARNING_ENGINEER: REJECTED
            CYBERSECURITY_ENGINEER: REJECTED
            DATA_ENGINEER: REJECTED
        }
    }
    """

    model = VALIDATOR.validate(text)

    assert model.experience is None
    assert model.education is None
    assert model.skills is None


def test_comments_are_ignored():
    assert VALIDATOR.is_valid("// profile generated by ResumeLens\n" + VALID)


# -------------------------------------------------------------------
# Lexical errors
# -------------------------------------------------------------------

def test_lexical_errors():
    assert_rejected(VALID.replace("REACT", "react"), TextXSyntaxError)
    assert_rejected(VALID.replace("DATA_ENGINEER: REJECTED", "DATA_ENGINEER: MAYBE"), TextXSyntaxError)
    assert_rejected(VALID.replace("wednesday@mail.com", "wednesday.mail.com"), TextXSyntaxError)
    assert_rejected(VALID.replace("years 3", "years three"), TextXSyntaxError)
    assert_rejected(VALID.replace("degree BACHELOR", "degree DIPLOMA"), TextXSyntaxError)
    assert_rejected(VALID.replace('"Wednesday Addams"', "Wednesday"), TextXSyntaxError)


def test_lexical_example_file():
    with pytest.raises(TextXSyntaxError):
        VALIDATOR.validate_file(PROFILES / "invalid_lexical.rl")


# -------------------------------------------------------------------
# Syntactic errors
# -------------------------------------------------------------------

def test_syntactic_errors():
    without_classification = VALID[:VALID.index("    classification")] + "}\n"
    without_last_brace = VALID.rstrip()[:-1]
    empty_category = VALID.replace("tools: GIT", "tools:")
    experience_without_entries = VALID.replace('        entry "3 years of experience"\n', "")

    a = VALID.index("    contact")
    b = VALID.index("    experience")
    c = VALID.index("    classification")
    contact_after_skills = VALID[:a] + VALID[b:c] + VALID[a:b] + VALID[c:]

    for text in (without_classification, without_last_brace, empty_category,
                 experience_without_entries, contact_after_skills):
        assert_rejected(text, TextXSyntaxError)


def test_syntactic_example_file():
    with pytest.raises(TextXSyntaxError):
        VALIDATOR.validate_file(PROFILES / "invalid_syntax.rl")


# -------------------------------------------------------------------
# Semantic errors
# -------------------------------------------------------------------

def test_token_must_belong_to_its_category():
    # MYSQL is not in the vocabulary; PYTHON is a language, not a tool.
    assert_rejected(VALID.replace("tools: GIT", "tools: GIT, MYSQL"), TextXSemanticError)
    assert_rejected(VALID.replace("tools: GIT", "tools: PYTHON"), TextXSemanticError)


def test_field_must_be_a_field_of_study():
    assert_rejected(VALID.replace("field COMPUTER_SCIENCE", "field BIOLOGY"), TextXSemanticError)


def test_repeated_skill_category():
    assert_rejected(VALID.replace("tools: GIT", "tools: GIT\n        tools: DOCKER"), TextXSemanticError)


def test_repeated_or_missing_profile():
    repeated = VALID.replace("DATA_ENGINEER: REJECTED", "FULL_STACK_DEVELOPER: REJECTED")
    missing = VALID.replace("        DATA_ENGINEER: REJECTED\n", "")

    assert_rejected(repeated, TextXSemanticError)
    assert_rejected(missing, TextXSemanticError)


def test_semantic_example_file():
    with pytest.raises(TextXSemanticError):
        VALIDATOR.validate_file(PROFILES / "invalid_semantic.rl")


def test_error_message_has_the_location():
    with pytest.raises(TextXSemanticError) as error:
        VALIDATOR.validate(VALID.replace("tools: GIT", "tools: GIT, MYSQL"))

    assert error.value.line == 18
    assert "MYSQL" in str(error.value)
